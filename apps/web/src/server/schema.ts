// Applied on first connection (idempotent). Keep statements portable between Neon and PGlite.

export const SCHEMA = [
  `CREATE TABLE IF NOT EXISTS users (
    address TEXT PRIMARY KEY,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS used_nonces (
    nonce TEXT PRIMARY KEY,
    used_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
  `CREATE TABLE IF NOT EXISTS api_keys (
    id TEXT PRIMARY KEY,
    owner TEXT NOT NULL REFERENCES users(address) ON DELETE CASCADE,
    name TEXT NOT NULL,
    prefix TEXT NOT NULL,
    key_hash TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ
  )`,
  `CREATE TABLE IF NOT EXISTS wallets (
    id TEXT PRIMARY KEY,
    owner TEXT NOT NULL REFERENCES users(address) ON DELETE CASCADE,
    address TEXT NOT NULL,
    label TEXT NOT NULL,
    kind TEXT NOT NULL DEFAULT 'monitor' CHECK (kind IN ('monitor', 'protected')),
    smart_account TEXT,
    vault TEXT,
    agent_signer TEXT,
    warden_key_ref TEXT,
    frozen BOOLEAN NOT NULL DEFAULT false,
    frozen_at TIMESTAMPTZ,
    sync_status TEXT NOT NULL DEFAULT 'pending',
    sync_error TEXT,
    backfilled_at TIMESTAMPTZ,
    newest_signature TEXT,
    last_synced_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (owner, address)
  )`,
  `CREATE INDEX IF NOT EXISTS wallets_address ON wallets (address)`,
  `CREATE TABLE IF NOT EXISTS policies (
    wallet_id TEXT NOT NULL REFERENCES wallets(id) ON DELETE CASCADE,
    version INT NOT NULL,
    template TEXT,
    policy JSONB NOT NULL,
    created_by TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (wallet_id, version)
  )`,
  `CREATE TABLE IF NOT EXISTS events (
    wallet_id TEXT NOT NULL REFERENCES wallets(id) ON DELETE CASCADE,
    signature TEXT NOT NULL,
    slot BIGINT,
    ts TIMESTAMPTZ NOT NULL,
    type TEXT NOT NULL,
    source TEXT,
    description TEXT,
    actions JSONB NOT NULL DEFAULT '[]',
    changes JSONB NOT NULL DEFAULT '[]',
    outflow_usd DOUBLE PRECISION,
    inflow_usd DOUBLE PRECISION,
    outflow_unpriced BOOLEAN NOT NULL DEFAULT false,
    counterparties TEXT[] NOT NULL DEFAULT '{}',
    recipients TEXT[] NOT NULL DEFAULT '{}',
    programs TEXT[] NOT NULL DEFAULT '{}',
    fee BIGINT,
    failed BOOLEAN NOT NULL DEFAULT false,
    signed_by_wallet BOOLEAN NOT NULL DEFAULT false,
    cosigned_by_warden BOOLEAN,
    PRIMARY KEY (wallet_id, signature)
  )`,
  `CREATE INDEX IF NOT EXISTS events_wallet_ts ON events (wallet_id, ts DESC)`,
  `CREATE TABLE IF NOT EXISTS checks (
    id TEXT PRIMARY KEY,
    wallet_id TEXT NOT NULL REFERENCES wallets(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    origin TEXT NOT NULL DEFAULT 'api',
    endpoint TEXT,
    message_hash TEXT NOT NULL,
    summary TEXT NOT NULL,
    actions JSONB NOT NULL,
    outflows JSONB NOT NULL,
    outflow_usd DOUBLE PRECISION,
    recipients JSONB NOT NULL,
    programs TEXT[] NOT NULL DEFAULT '{}',
    stages JSONB NOT NULL,
    reasons JSONB NOT NULL,
    score INT NOT NULL,
    verdict TEXT NOT NULL,
    enforced TEXT NOT NULL,
    mode TEXT NOT NULL,
    policy_version INT,
    model_used BOOLEAN NOT NULL DEFAULT false,
    context_hash TEXT,
    context_excerpt JSONB,
    latency_ms INT NOT NULL,
    stage_ms JSONB NOT NULL DEFAULT '{}',
    transaction TEXT,
    status TEXT NOT NULL
  )`,
  `CREATE INDEX IF NOT EXISTS checks_wallet_time ON checks (wallet_id, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS holds (
    check_id TEXT PRIMARY KEY REFERENCES checks(id) ON DELETE CASCADE,
    wallet_id TEXT NOT NULL REFERENCES wallets(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    decision TEXT CHECK (decision IN ('approved', 'denied', 'expired')),
    decided_by TEXT,
    decided_at TIMESTAMPTZ
  )`,
  `CREATE TABLE IF NOT EXISTS overrides (
    check_id TEXT NOT NULL REFERENCES checks(id) ON DELETE CASCADE,
    owner TEXT NOT NULL,
    action TEXT NOT NULL,
    label TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (check_id, action)
  )`,
  `CREATE TABLE IF NOT EXISTS alerts (
    id TEXT PRIMARY KEY,
    owner TEXT NOT NULL REFERENCES users(address) ON DELETE CASCADE,
    wallet_id TEXT REFERENCES wallets(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    severity TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'critical')),
    type TEXT NOT NULL,
    title TEXT NOT NULL,
    body TEXT NOT NULL,
    ref TEXT,
    dedupe_key TEXT UNIQUE,
    delivered JSONB NOT NULL DEFAULT '[]',
    read_at TIMESTAMPTZ
  )`,
  `CREATE INDEX IF NOT EXISTS alerts_owner_time ON alerts (owner, created_at DESC)`,
  `CREATE TABLE IF NOT EXISTS alert_channels (
    id TEXT PRIMARY KEY,
    owner TEXT NOT NULL REFERENCES users(address) ON DELETE CASCADE,
    kind TEXT NOT NULL CHECK (kind IN ('webhook', 'telegram', 'slack', 'email')),
    label TEXT NOT NULL,
    config JSONB NOT NULL,
    min_severity TEXT NOT NULL DEFAULT 'warning',
    enabled BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_error TEXT
  )`,
  `CREATE TABLE IF NOT EXISTS entities (
    kind TEXT NOT NULL CHECK (kind IN ('address', 'program', 'endpoint', 'source')),
    key TEXT NOT NULL,
    score INT NOT NULL,
    reasons JSONB NOT NULL DEFAULT '[]',
    signals JSONB NOT NULL DEFAULT '{}',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (kind, key)
  )`,
  `CREATE TABLE IF NOT EXISTS reports (
    id TEXT PRIMARY KEY,
    reporter TEXT NOT NULL,
    kind TEXT NOT NULL,
    key TEXT NOT NULL,
    category TEXT NOT NULL,
    note TEXT,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'rejected')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
  )`,
]
